import * as crypto from 'crypto';
import * as path from 'path';
import * as fs from 'fs';

// fabric-network types — install: npm install fabric-network @types/fabric-network
// Using dynamic import to allow the service to fail-open when Fabric is unavailable.
// The type import is kept separate so TypeScript can still type-check the code.
type Gateway = import('fabric-network').Gateway;
type Network = import('fabric-network').Network;
type Contract = import('fabric-network').Contract;

// ─── CONFIG ──────────────────────────────────────────────────────────────────

const FABRIC_CONFIG = {
  channel:    process.env.FABRIC_CHANNEL    ?? 'nexusid-channel',
  chaincode:  process.env.FABRIC_CHAINCODE  ?? 'credential-audit',
  /** Path to the connection profile JSON generated by fabric-setup.sh */
  ccpPath:    process.env.FABRIC_CCP_PATH   ?? path.resolve(__dirname, '../../../../blockchain/network/connection-profile.json'),
  /** MSP ID of the identity submitting transactions */
  mspId:      process.env.FABRIC_MSP_ID     ?? 'Org1MSP',
  /** Wallet label for the admin identity */
  walletLabel: process.env.FABRIC_WALLET_LABEL ?? 'admin',
  /** Path to the Fabric wallet directory */
  walletPath:  process.env.FABRIC_WALLET_PATH  ?? path.resolve(__dirname, '../../../../blockchain/network/wallet'),
};

// ─── TYPES ────────────────────────────────────────────────────────────────────

export interface RevocationStatus {
  revoked: boolean;
  reason?: string;
  revokedAt?: string;
  found?: boolean;
}

export interface IssuanceRecord {
  credentialId: string;
  issuerDID: string;
  subjectHash: string;
  credentialType: string;
  event: 'ISSUED';
  timestamp: string;
  txId: string;
  revoked: boolean;
  revocationReason: string | null;
  revocationTimestamp: string | null;
}

export interface HistoryEntry {
  txId: string;
  timestamp: string | null;
  isDelete: boolean;
  value: IssuanceRecord | null;
}

// ─── SERVICE ─────────────────────────────────────────────────────────────────

class BlockchainService {
  private gateway: Gateway | null = null;
  private network: Network | null = null;
  private contract: Contract | null = null;
  private connected: boolean = false;

  // ── Connection Management ─────────────────────────────────────────────────

  /**
   * connect — establish connection to the Fabric gateway.
   * Call once at app startup. Throws if the connection profile or wallet
   * is missing; callers should catch and log — Fabric is non-critical.
   */
  async connect(): Promise<void> {
    if (this.connected) {
      console.log('[BlockchainService] Already connected.');
      return;
    }

    // Dynamically import fabric-network so the app still starts if it's not installed
    let fabricNetwork: typeof import('fabric-network');
    try {
      fabricNetwork = await import('fabric-network');
    } catch {
      throw new Error(
        '[BlockchainService] fabric-network package not installed. ' +
        'Run: npm install fabric-network  (in services/backend)'
      );
    }

    // Load connection profile
    if (!fs.existsSync(FABRIC_CONFIG.ccpPath)) {
      throw new Error(
        `[BlockchainService] Connection profile not found at: ${FABRIC_CONFIG.ccpPath}\n` +
        'Run scripts/fabric-setup.sh to generate it.'
      );
    }
    const ccp = JSON.parse(fs.readFileSync(FABRIC_CONFIG.ccpPath, 'utf8'));

    // Set up file-system wallet
    const wallet = await fabricNetwork.Wallets.newFileSystemWallet(FABRIC_CONFIG.walletPath);
    const identity = await wallet.get(FABRIC_CONFIG.walletLabel);
    if (!identity) {
      throw new Error(
        `[BlockchainService] Identity "${FABRIC_CONFIG.walletLabel}" not found in wallet at ${FABRIC_CONFIG.walletPath}.\n` +
        'Enroll the admin user with enrollAdmin.ts before connecting.'
      );
    }

    const gateway = new fabricNetwork.Gateway();
    await gateway.connect(ccp, {
      wallet,
      identity: FABRIC_CONFIG.walletLabel,
      discovery: { enabled: true, asLocalhost: true },
    });

    this.gateway = gateway;
    this.network  = await gateway.getNetwork(FABRIC_CONFIG.channel);
    this.contract = this.network.getContract(FABRIC_CONFIG.chaincode);
    this.connected = true;

    console.log(
      `[BlockchainService] Connected to Fabric — channel: ${FABRIC_CONFIG.channel}, chaincode: ${FABRIC_CONFIG.chaincode}`
    );
  }

  /** disconnect — close the Fabric gateway. Call on app shutdown. */
  disconnect(): void {
    if (this.gateway) {
      this.gateway.disconnect();
      this.gateway  = null;
      this.network  = null;
      this.contract = null;
      this.connected = false;
      console.log('[BlockchainService] Disconnected from Fabric gateway.');
    }
  }

  // ── Core Operations ───────────────────────────────────────────────────────

  /**
   * logCredentialIssuance — record a credential issuance on-chain.
   * Fails silently: a Fabric outage must never block credential issuance.
   *
   * @param credentialId  UUID of the issued credential
   * @param issuerDID     e.g. 'nadra.gov.pk'
   * @param subject       Raw subject (CNIC, reg number) — will be SHA-256 hashed before ledger write
   * @param credentialType 'identity' | 'education' | 'employment' | 'enrollment'
   */
  async logCredentialIssuance(
    credentialId: string,
    issuerDID: string,
    subject: string,
    credentialType: string,
  ): Promise<void> {
    try {
      const contract = this._requireContract();

      const subjectHash = _sha256(subject);
      const timestamp   = new Date().toISOString();

      await contract.submitTransaction(
        'logIssuance',
        credentialId,
        issuerDID,
        subjectHash,
        credentialType,
        timestamp,
      );

      console.log(`[BlockchainService] Issuance logged: ${credentialId} (type: ${credentialType})`);
    } catch (err) {
      // Fail silently — Fabric audit trail is not on the critical path
      console.error('[BlockchainService] logCredentialIssuance failed (non-fatal):', err);
    }
  }

  /**
   * logVerification — record a credential verification event on-chain.
   * Fails silently.
   *
   * @param credentialId    UUID of the credential used
   * @param verifierId      Verifier domain (e.g. 'jobportal.com') — will be SHA-256 hashed
   * @param disclosedFields Array of field NAMES that were disclosed (no values)
   */
  async logVerification(
    credentialId: string,
    verifierId: string,
    disclosedFields: string[],
  ): Promise<void> {
    try {
      const contract = this._requireContract();

      const verifierIdHash = _sha256(verifierId);
      const timestamp      = new Date().toISOString();

      await contract.submitTransaction(
        'logVerification',
        credentialId,
        verifierIdHash,
        JSON.stringify(disclosedFields),
        timestamp,
      );

      console.log(
        `[BlockchainService] Verification logged: ${credentialId} ` +
        `(fields: ${disclosedFields.join(', ')})`
      );
    } catch (err) {
      console.error('[BlockchainService] logVerification failed (non-fatal):', err);
    }
  }

  /**
   * logRevocation — record a credential revocation on-chain.
   * Fails silently.
   */
  async logRevocation(
    credentialId: string,
    reason: string,
  ): Promise<void> {
    try {
      const contract = this._requireContract();
      const timestamp = new Date().toISOString();

      await contract.submitTransaction(
        'revokeCredential',
        credentialId,
        reason,
        timestamp,
      );

      console.log(`[BlockchainService] Revocation logged: ${credentialId}`);
    } catch (err) {
      console.error('[BlockchainService] logRevocation failed (non-fatal):', err);
    }
  }

  /**
   * checkRevocation — query on-chain revocation status.
   * This is an evaluate (read-only) transaction — no ledger write, no ordering.
   * Returns { revoked: false } if Fabric is unavailable (fail-open).
   */
  async checkRevocation(credentialId: string): Promise<RevocationStatus> {
    try {
      const contract = this._requireContract();

      const result = await contract.evaluateTransaction('checkRevocation', credentialId);
      const parsed = JSON.parse(result.toString()) as RevocationStatus;

      return parsed;
    } catch (err) {
      console.error('[BlockchainService] checkRevocation failed:', err);
      // Fail open — don't block verification if Fabric is down
      return { revoked: false };
    }
  }

  /**
   * getCredentialHistory — retrieve the full ledger history for a credential.
   * Returns empty array if unavailable.
   */
  async getCredentialHistory(credentialId: string): Promise<HistoryEntry[]> {
    try {
      const contract = this._requireContract();

      const result = await contract.evaluateTransaction('getCredentialHistory', credentialId);
      return JSON.parse(result.toString()) as HistoryEntry[];
    } catch (err) {
      console.error('[BlockchainService] getCredentialHistory failed:', err);
      return [];
    }
  }

  /**
   * getIssuanceRecord — retrieve the current issuance state for a credential.
   */
  async getIssuanceRecord(credentialId: string): Promise<IssuanceRecord | null> {
    try {
      const contract = this._requireContract();

      const result = await contract.evaluateTransaction('getIssuanceRecord', credentialId);
      return JSON.parse(result.toString()) as IssuanceRecord;
    } catch (err) {
      console.error('[BlockchainService] getIssuanceRecord failed:', err);
      return null;
    }
  }

  // ── Status ────────────────────────────────────────────────────────────────

  isConnected(): boolean {
    return this.connected;
  }

  // ── Private ───────────────────────────────────────────────────────────────

  private _requireContract(): Contract {
    if (!this.contract || !this.connected) {
      throw new Error(
        '[BlockchainService] Not connected to Fabric. ' +
        'Call connect() first, or check that the Fabric network is running.'
      );
    }
    return this.contract;
  }
}

// ─── HELPERS ─────────────────────────────────────────────────────────────────

/** SHA-256 hash of a string → hex digest */
function _sha256(input: string): string {
  return crypto.createHash('sha256').update(input, 'utf8').digest('hex');
}

// ─── SINGLETON EXPORT ────────────────────────────────────────────────────────

export const blockchainService = new BlockchainService();
export default blockchainService;
