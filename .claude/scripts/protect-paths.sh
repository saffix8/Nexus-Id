#!/usr/bin/env bash
set -euo pipefail

input=$(cat)
path=$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty')
[ -z "$path" ] && exit 0

case "$path" in
  *.env|*.env.*|*/.env*)
    echo "Blocked: environment files are edited by hand only." >&2; exit 2 ;;
  *.pem|*.jwk|*.keystore|*/keys/*)
    echo "Blocked: key material is generated by the key scripts, never edited." >&2; exit 2 ;;
  */node_modules/*|*/.next/*|*/dist/*|*/build/*)
    echo "Blocked: generated output. Change the source instead." >&2; exit 2 ;;
  */prisma/migrations/*)
    echo "Blocked: applied migrations are immutable. Create a new migration." >&2; exit 2 ;;
  *.bak)
    echo "Blocked: backup files are evidence. Leave them alone." >&2; exit 2 ;;
esac

exit 0
